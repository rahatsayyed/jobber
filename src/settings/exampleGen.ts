// src/settings/exampleGen.ts
// Renders .env.example from the settings catalog (plan 8H, Task 3). Pure: no file access, same input, same bytes.
// Format rules the loaders need: comments sit on their own line ABOVE the key (never after a value), active keys are
// `KEY=value`, optional keys are `# KEY=value` (the value shown is the code default), secrets ship blank.
import type { EnvSpec, SectionId } from './types.js';

const WIDTH = 100;

export interface SectionBanner {
  title: string;
  lines?: string[];
}

