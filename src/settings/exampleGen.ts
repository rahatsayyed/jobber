/** The header block, verbatim from the hand-written file, plus the generated-file notice. */
export const ENV_EXAMPLE_HEADER = `# Jobber environment file.
#
# GENERATED by \`npm run env:example\` from src/settings/envCatalog.ts. Do not edit it by hand: change the
# catalog and regenerate (\`npm run env:example -- --check\` fails on drift).
#
# Copy this file to \`.env\` (mode 600, gitignored) and fill in the values, or run \`npm run setup\`,
# which writes the values for you. \`.env.example\` itself is committed and holds no secrets.
#
# Format rules (every loader in this project reads the file the same way):
# - One \`KEY=value\` per line. Surrounding single or double quotes are stripped, nothing else.
# - NEVER put a comment after a value on the same line: the loaders read the inline comment as
#   part of the value, so \`MATCH_THRESHOLD=60  # note\` makes the limit invalid. Comments go on
#   their own line above the key.
# - A blank value (\`KEY=\`) means "not set". A commented-out line (\`# KEY=value\`) is an optional
#   setting that stays unset by default; the value shown is the code default.
# - Nothing here is sourced into a shell. Launchers parse the file and pass an allowlisted
#   environment to child processes.
# - Defaults, ranges and meanings of the numeric limits also live in src/setup/limitsCatalog.ts.
`;

const RULE =`# ${'='.repeat(85)}`;

function wrap(text: string, prefix = '# '): string[] {
  const out: string[] = [];
  let cur = '';
  for (const w of text.split(/\s+/).filter(Boolean)) {
    if (cur !== '' && (prefix + cur + ' ' + w).length > WIDTH) {
      out.push(prefix + cur);
      cur = w;
    } else cur = cur === '' ? w : `${cur} ${w}`;
  }
  if (cur !== '') out.push(prefix + cur);
  return out;
}

function ensureDot(s: string): string {
  return /[.:)]$/.test(s) ? s : `${s}.`;
}

/** The comment text above a key: the about text plus the structured facts the about does not already state. */
export function commentFor(s: EnvSpec): string {
  const parts: string[] = [ensureDot(s.about.trim())];
  const about = s.about;
  if (s.default !== null && !s.secret && s.type !== 'secret' && !/\bDefault\b/i.test(about)) parts.push(`Default ${s.default}.`);
  if (s.type === 'int' && s.min !== undefined && s.max !== undefined && !/\d+\.\.\d+/.test(about)) {
    parts.push(`Integer ${s.min}..${s.max}.`);
  }
  if (s.allowed && s.allowed.length > 0 && !/\bAllowed\b/.test(about)) parts.push(`Allowed: ${s.allowed.join(', ')}.`);
  else if (s.type === 'bool' && !/\bAllowed\b/.test(about) && !s.allowed) parts.push('Allowed: true or false.');
  if (s.secret || s.type === 'secret') {
    if (!/\bSecret\b/.test(about)) parts.push('Secret.');
  }
  if (s.required === 'required' && !/\brequired\b/i.test(about)) parts.push('Required.');
  else if (s.required === 'conditional' && s.requiredWhen && !/\b(required|needed)\b/i.test(about)) {
    parts.push(`Required when ${s.requiredWhen}.`);
  }
  return parts.join(' ');
}

/** The value printed on the key line: a secret is always blank, otherwise the example value or the code default. */
export function shownValue(s: EnvSpec): string {
  if (s.secret || s.type === 'secret') return '';
  return s.exampleValue ?? s.default ?? '';
}

export function renderEnvExample(catalog: EnvSpec[], header: string): string {
  const out: string[] = [header.replace(/\n+$/, ''), ''];
  let section: SectionId | null = null;
  for (const s of catalog) {
    if (s.section !== section) {
      section = s.section;
      const b = SECTION_BANNERS[s.section];
      if (out[out.length - 1] !== '') out.push('');
      out.push(RULE, `# ${b.title}`);
      for (const l of b.lines ?? []) out.push(`# ${l}`);
      out.push(RULE, '');
    }
    out.push(...wrap(commentFor(s)));
    out.push(`${s.exampleActive ? '' : '# '}${s.key}=${shownValue(s)}`);
  }
  return out.join('\n').replace(/\n+$/, '') + '\n';
}
