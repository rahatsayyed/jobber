import { isSafeArchivePath } from './manifest.js';

export interface ArchiveEntry {
  archivePath: string;
  source: string;
  kind: 'db' | 'file' | 'dir';
  why: string;
}
export interface Excluded {
  path: string;
  why: string;
}

const SECRETS_WHY = 'credentials are re-creatable and are the highest-value target; opt in with BACKUP_INCLUDE_SECRETS=true';

const ALWAYS_EXCLUDED: { path: string; why: string }[] = [
  { path: 'node_modules', why: 'reinstalled with npm ci' },
  { path: '.git', why: 'the repository is its own backup' },
  { path: '.ccgram', why: 'bridge state is re-creatable and holds session maps' },
  { path: 'reports', why: 'regenerated by npm run report' },
  { path: 'debug', why: 'debug output' },
  { path: 'scripts/eval/runs', why: 'regenerated eval output' },
  { path: '.backups', why: 'backup output must not contain itself' },
  { path: '.update', why: 'update runner scratch state' },
  { path: 'data.sqlite-wal', why: 'WAL file; the snapshot is used instead' },
  { path: 'data.sqlite-shm', why: 'shared-memory file; the snapshot is used instead' },
  { path: 'data.sqlite-journal', why: 'journal file; the snapshot is used instead' },
];

/** Entries come from an explicit allow-list; the project root is never walked. */
export function planEntries(
  root: string,
  ex: { exists(p: string): boolean; list(dir: string): string[] },
  cfg: { includeSecrets: boolean },
  dbSnapshotPath: string,
): { entries: ArchiveEntry[]; excluded: Excluded[] } {
  void root;
  const entries: ArchiveEntry[] = [];
  const excluded: Excluded[] = [];

  const add = (e: ArchiveEntry): void => {
    if (!isSafeArchivePath(e.archivePath)) {
      excluded.push({ path: e.archivePath, why: 'unsafe archive path' });
      return;
    }
    entries.push(e);
  };

  add({
    archivePath: 'data.sqlite',
    source: dbSnapshotPath,
    kind: 'db',
    why: 'the database (online snapshot, never the live file): everything the owner would lose',
  });

  if (ex.exists('user-data')) {
    add({ archivePath: 'user-data', source: 'user-data', kind: 'dir', why: 'irreplaceable personal inputs (resume, answers, fact-gate, languages)' });
  }

  if (ex.exists('config')) {
    for (const name of ex.list('config')) {
      if (name.endsWith('.bak')) {
        excluded.push({ path: `config/${name}`, why: 'backup copy (*.bak)' });
      } else if (name.endsWith('.json')) {
        add({ archivePath: `config/${name}`, source: `config/${name}`, kind: 'file', why: 'local tuning may be uncommitted' });
      }
    }
  }

  for (const f of ['.claude/settings.local.json', '.claude/settings.local.managed.json']) {
    if (ex.exists(f)) add({ archivePath: f, source: f, kind: 'file', why: 'chosen permission set and managed entries' });
  }

  if (ex.exists('.env')) {
    if (cfg.includeSecrets) add({ archivePath: '.env', source: '.env', kind: 'file', why: 'opted in with BACKUP_INCLUDE_SECRETS=true' });
    else excluded.push({ path: '.env', why: SECRETS_WHY });
  }
  if (ex.exists('secrets')) {
    if (cfg.includeSecrets) add({ archivePath: 'secrets', source: 'secrets', kind: 'dir', why: 'opted in with BACKUP_INCLUDE_SECRETS=true' });
    else excluded.push({ path: 'secrets', why: SECRETS_WHY });
  }

  for (const a of ALWAYS_EXCLUDED) {
    if (ex.exists(a.path)) excluded.push({ path: a.path, why: a.why });
  }

  return { entries, excluded };
}
